/**
 * Write public/models/CREDITS.md for every picked candidate in tools/assets/sources.json.
 *
 *   node tools/assets/credits.mjs
 *
 * CC-BY 4.0 requires title, author, source, licence and an indication of changes; all of
 * them are recorded by fetch.mjs. Any picked candidate with another licence fails the run.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { LICENSES, readManifest } from "./fetch.mjs"

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.resolve(HERE, "../../public/models/CREDITS.md")
const CHANGES =
  "Converted to glTF, rescaled to real-world size, re-oriented, materials remapped to the scene palette (textures flattened), decimated and split into animated parts where needed."

const manifest = readManifest()
const rows = []
const bad = []
for (const [slot, def] of Object.entries(manifest.slots)) {
  if (!def.pick) continue
  const c = def.candidates.find((x) => x.id === def.pick)
  if (!c) {
    bad.push(`${slot}: pick "${def.pick}" is not a candidate`)
    continue
  }
  const lic = LICENSES[c.license]
  if (!lic) {
    bad.push(`${slot}: licence "${c.license}" not allowed`)
    continue
  }
  rows.push({ slot, c, lic })
}
if (bad.length) {
  console.error(bad.join("\n"))
  process.exit(1)
}

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|")
const link = (text, url) => (url ? `[${esc(text)}](${url})` : esc(text))
const third = rows.filter(
  (r) =>
    r.c.license === "by" || r.c.license === "cc0" || r.c.license === "upload",
)
const nv = rows.filter((r) => r.c.license === "nvidia")
let md = `# Third-party model credits\n\nGenerated by \`tools/assets/credits.mjs\` from \`tools/assets/sources.json\`. ${CHANGES}\n\n`
md += `| File | Model | Author | Licence |\n| --- | --- | --- | --- |\n`
for (const { slot, c, lic } of third)
  md += `| \`${slot}.glb\` | ${link(c.title, c.url)} | ${link(c.author, c.authorUrl)} | ${link(lic.id, lic.url)} |\n`
if (nv.length) {
  md += `\nNVIDIA Omniverse / SimReady assets (see also \`README.md\`), used under the ${link(LICENSES.nvidia.id, LICENSES.nvidia.url)}:\n\n`
  for (const { slot, c } of nv)
    md += `- \`${slot}.glb\` — \`${c.usd ?? c.src}\`\n`
}
fs.writeFileSync(OUT, md)
console.log(
  `wrote ${path.relative(process.cwd(), OUT)} (${rows.length} models)`,
)
